package io.earthplatform.minecraft.cubic.client;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import org.junit.jupiter.api.Test;

/**
 * Tests the Tier 3 shader-pack path ({@link FarShaders#terrainPatch},
 * {@link FarShaders#terrainVertex}, {@link FarShaders#terrainFragment}) used for packs with neither
 * Voxy nor Distant Horizons support (such as SEUS Renewed).
 */
class FarTerrainPackTest {
    /**
     * SEUS-like GLSL 120 {@code gbuffers_terrain} vertex shader as left by Iris's
     * {@code TransformPatcher.patchVanilla}: all built-in matrices, fog, attributes, and
     * {@code ftransform()} rewritten to Iris's core-profile names.
     */
    private static final String SEUS_PATCHED_VERTEX = """
            #version 330 core
            // Generated by glsl-transformer
            uniform mat4 iris_ProjMat;
            in vec3 iris_Position;
            uniform mat4 iris_ModelViewMatInverse;
            uniform mat4 iris_ProjMatInverse;
            uniform mat3 iris_NormalMat;
            uniform mat4 iris_LightmapTextureMatrix;
            uniform mat4 iris_TextureMat;
            uniform mat4 iris_ModelViewMat;
            in vec3 iris_Normal;
            in vec4 iris_Color;
            uniform vec4 iris_ColorModulator;
            in ivec2 iris_UV2;
            in vec2 iris_UV0;
            uniform float iris_FogDensity;
            uniform float iris_FogStart;
            uniform float iris_FogEnd;
            uniform vec4 iris_FogColor;
            struct iris_FogParameters {
                vec4 color;
                float density;
                float start;
                float end;
                float scale;
            };
            iris_FogParameters iris_Fog = iris_FogParameters(iris_FogColor, iris_FogDensity, iris_FogStart, iris_FogEnd, 1.0f / (iris_FogEnd - iris_FogStart));
            vec4 iris_FrontColor;
            out float iris_FogFragCoord;
            in vec4 mc_Entity;
            in vec4 at_tangent;
            out vec4 color;
            out vec4 texcoord;
            out vec4 lmcoord;
            out vec3 normal;
            out vec3 tangent;
            out float isWater;
            vec4 ftransform() {
                return (iris_ProjMat * (iris_ModelViewMat)) * vec4(iris_Position, 1.0f);
            }
            void helper(in vec3 p, out vec3 copy) {
                copy = p;
            }
            void main() {
                iris_FogFragCoord = 0.0f;
                vec3 p;
                helper(vec4(iris_Position, 1.0f).xyz, p);
                gl_Position = ftransform();
                color = (iris_Color * iris_ColorModulator);
                texcoord = iris_TextureMat * vec4(iris_UV0, 0.0f, 1.0f);
                lmcoord = iris_LightmapTextureMatrix * vec4(iris_UV2, 0.0f, 1.0f);
                normal = normalize(iris_NormalMat * iris_Normal);
                tangent = normalize(iris_NormalMat * at_tangent.xyz);
                isWater = (mc_Entity.x == 8.0f || mc_Entity.x == 9.0f) ? 1.0f : 0.0f;
            }
            """;

    /** Matching SEUS-like GLSL 120 {@code gbuffers_terrain} fragment shader writing 4 MRT targets. */
    private static final String SEUS_PATCHED_FRAGMENT = """
            #version 330 core
            // Generated by glsl-transformer
            layout(location = 3) out vec4 iris_FragData3;
            layout(location = 2) out vec4 iris_FragData2;
            layout(location = 1) out vec4 iris_FragData1;
            layout(location = 0) out vec4 iris_FragData0;
            in float iris_FogFragCoord;
            uniform sampler2D gtexture;
            uniform sampler2D lightmap;
            in vec4 color;
            in vec4 texcoord;
            in vec4 lmcoord;
            in vec3 normal;
            in vec3 tangent;
            in float isWater;
            void main() {
                vec4 albedo = texture(gtexture, texcoord.st) * color;
                iris_FragData0 = albedo;
                iris_FragData1 = vec4(normal * 0.5f + 0.5f, 1.0f);
                iris_FragData2 = vec4(lmcoord.st, isWater, 1.0f);
                iris_FragData3 = vec4(tangent * 0.5f + 0.5f, 1.0f);
            }
            """;

    /** Modern GLSL 330 core {@code gbuffers_terrain_solid} vertex shader as left by Iris's vanilla patcher. */
    private static final String CORE_PATCHED_VERTEX = """
            #version 330 core
            #extension GL_ARB_explicit_attrib_location : enable
            in vec2 iris_UV1;
            uniform vec4 iris_ColorModulator;
            in vec4 iris_Color;
            in vec3 iris_Position;
            in vec4 vaColor;
            in vec3 iris_Normal;
            in vec2 iris_UV0;
            in ivec2 iris_UV2;
            in vec4 mc_Entity;
            in vec3 at_midBlock;
            in vec4 mc_midTexCoord;
            layout(location = 7) flat in ivec3 iris_Entity;
            uniform mat4 iris_ModelViewMat;
            uniform mat4 iris_ProjMat;
            uniform mat3 iris_NormalMat;
            uniform vec3 iris_ChunkOffset;
            out vec4 vColor;
            out vec2 vUv;
            out vec2 vLm;
            out vec3 vNormal;
            void main() {
                vec3 worldPos = iris_Position + iris_ChunkOffset + at_midBlock * 0.0f;
                gl_Position = iris_ProjMat * iris_ModelViewMat * vec4(worldPos, 1.0f);
                vColor = iris_Color * iris_ColorModulator;
                vUv = iris_UV0 + mc_midTexCoord.xy * 0.0f;
                vLm = vec2(iris_UV2) / 240.0f;
                vNormal = normalize(iris_NormalMat * iris_Normal) + mc_Entity.xyz * 0.0f + vec3(iris_Entity) * 0.0f;
            }
            """;

    /** Modern GLSL 330 core {@code gbuffers_terrain_solid} fragment shader writing 4 RENDERTARGETS. */
    private static final String CORE_PATCHED_FRAGMENT = """
            #version 330 core
            uniform sampler2D gtexture;
            uniform sampler2D lightmap;
            in vec4 vColor;
            in vec2 vUv;
            in vec2 vLm;
            in vec3 vNormal;
            layout(location = 0) out vec4 col0;
            layout(location = 1) out vec4 col1;
            layout(location = 2) out vec4 col2;
            layout(location = 3) out vec4 col3;
            void main() {
                col0 = texture(gtexture, vUv) * vColor;
                col1 = vec4(vNormal * 0.5f + 0.5f, 1.0f);
                col2 = vec4(vLm, 0.0f, 1.0f);
                col3 = texture(lightmap, vLm);
            }
            """;

    @Test void splicesSeusLikeGlsl120MultiTargetTerrainProgram() {
        FarShaders.PackPatch patch = FarShaders.terrainPatch(SEUS_PATCHED_VERTEX, SEUS_PATCHED_FRAGMENT, 4);
        assertNotNull(patch);
        assertTrue(patch.terrain());
        assertFalse(patch.dh());
        assertFalse(patch.ownDepth());
        assertEquals(4, patch.outputs());

        String vertex = FarShaders.terrainVertex("#version 330 core\n", patch);
        assertEquals(1, count(vertex, "#version"), vertex);
        assertEquals(1, count(vertex, "void main()"), vertex);
        assertTrue(vertex.contains("void earth_main()"), vertex);
        assertTrue(vertex.contains("void earth_terrainInit()"), vertex);
        assertTrue(vertex.contains("void earth_terrainAssign()"), vertex);
        assertTrue(vertex.contains("void earth_terrainMain()"), vertex);
        // All vertex attributes are converted to globals and assigned from far terrain's unpacked face.
        assertFalse(vertex.contains("in vec3 iris_Position;"), vertex);
        assertFalse(vertex.contains("in vec4 iris_Color;"), vertex);
        assertFalse(vertex.contains("in vec3 iris_Normal;"), vertex);
        assertFalse(vertex.contains("in vec2 iris_UV0;"), vertex);
        assertFalse(vertex.contains("in ivec2 iris_UV2;"), vertex);
        assertFalse(vertex.contains("in vec4 mc_Entity;"), vertex);
        assertFalse(vertex.contains("in vec4 at_tangent;"), vertex);
        assertTrue(vertex.contains("iris_Position = earth_terrainPosition;"), vertex);
        assertTrue(vertex.contains("iris_Normal = earth_terrainNormal;"), vertex);
        assertTrue(vertex.contains("iris_Color = earth_terrainColour;"), vertex);
        assertTrue(vertex.contains("iris_UV0 = earth_terrainUv;"), vertex);
        assertTrue(vertex.contains("iris_UV2 = earth_terrainLight;"), vertex);
        assertTrue(vertex.contains("at_tangent = earth_terrainTangent;"), vertex);
        assertTrue(vertex.contains("mc_Entity = vec4(-1.0, 0.0, 0.0, 0.0);"), vertex);
        // Function parameter qualifiers must remain untouched.
        assertTrue(vertex.contains("in vec3 p") && vertex.contains("out vec3 copy"), vertex);

        String fragment = FarShaders.terrainFragment("#version 330 core\n", patch, FarGpu.FADE_IN, true);
        assertEquals(1, count(fragment, "#version"), fragment);
        assertEquals(1, count(fragment, "void main()"), fragment);
        assertTrue(fragment.contains("#define EARTH_GROUND"), fragment);
        assertTrue(fragment.contains("#define EARTH_FADE 2"), fragment);
        assertFalse(fragment.contains("earth_faceDepth"), fragment);
        // All 4 MRT outputs are preserved intact.
        for (int i = 0; i < 4; i++) {
            assertTrue(fragment.contains("iris_FragData" + i), "missing output " + i + ":\n" + fragment);
        }
        assertTrue(fragment.indexOf("void earth_terrainBefore()") < fragment.indexOf("void earth_terrainMain()"), fragment);
        assertTrue(fragment.indexOf("earth_terrainBefore();\n    earth_terrainMain();") > fragment.indexOf("void earth_terrainMain()"), fragment);
    }

    @Test void splicesModernGlsl330CoreMultiTargetTerrainProgram() {
        FarShaders.PackPatch patch = FarShaders.terrainPatch(CORE_PATCHED_VERTEX, CORE_PATCHED_FRAGMENT, 4);
        assertNotNull(patch);
        assertTrue(patch.terrain());
        assertFalse(patch.dh());
        assertFalse(patch.ownDepth());

        String vertex = FarShaders.terrainVertex("#version 330 core\n", patch);
        assertEquals(1, count(vertex, "#version"), vertex);
        assertEquals(1, count(vertex, "void main()"), vertex);
        // Extensions follow the version line.
        assertTrue(vertex.startsWith("#version 330 core\n#extension GL_ARB_explicit_attrib_location : enable\n"), vertex);
        assertTrue(vertex.contains("iris_Position = earth_terrainPosition;"), vertex);
        assertTrue(vertex.contains("iris_Normal = earth_terrainNormal;"), vertex);
        assertTrue(vertex.contains("iris_Color = earth_terrainColour;"), vertex);
        assertTrue(vertex.contains("iris_UV0 = earth_terrainUv;"), vertex);
        assertTrue(vertex.contains("iris_UV1 = vec2(0.0, 10.0);"), vertex);
        assertTrue(vertex.contains("iris_UV2 = earth_terrainLight;"), vertex);
        assertTrue(vertex.contains("mc_midTexCoord = vec4(earth_terrainUv, 0.0, 1.0);"), vertex);
        assertTrue(vertex.contains("iris_Entity = ivec3(-1, -1, -1);"), vertex);
        assertTrue(vertex.contains("at_midBlock = vec3(0);"), vertex);
        assertTrue(vertex.contains("vaColor = vec4(0);"), vertex);
        assertFalse(vertex.contains("flat in ivec3 iris_Entity"), vertex);

        String fragment = FarShaders.terrainFragment("#version 330 core\n", patch, FarGpu.NO_FADE, false);
        assertEquals(1, count(fragment, "void main()"), fragment);
        for (int i = 0; i < 4; i++) {
            assertTrue(fragment.contains("location = " + i) && fragment.contains("col" + i), "missing core MRT target " + i + ":\n" + fragment);
        }
    }

    @Test void rejectsUnpatchedOrEmptyTerrainPrograms() {
        assertNull(FarShaders.terrainPatch("#version 330 core\nvoid main() { gl_Position = vec4(0.0); }\n", CORE_PATCHED_FRAGMENT, 4));
        assertNull(FarShaders.terrainPatch(null, CORE_PATCHED_FRAGMENT, 4));
        assertNull(FarShaders.terrainPatch(CORE_PATCHED_VERTEX, null, 4));
        assertNull(FarShaders.terrainPatch("#version 330 core\nin vec3 iris_Position;\nvoid main() { gl_Position = vec4(iris_Position, 1.0); }\n",
                CORE_PATCHED_FRAGMENT, 0));
    }

    @Test void packPatchTiersKeepDistinctFlags() {
        FarShaders.PackPatch voxy = new FarShaders.PackPatch("layout(location = 0) out vec4 col0;\nvoid voxy_emitFragment(VoxyFragmentParameters p) { col0 = p.sampledColour; }", null);
        assertFalse(voxy.dh());
        assertFalse(voxy.terrain());
        assertTrue(voxy.ownDepth());
    }

    private static int count(String text, String part) {
        int count = 0;
        for (int at = text.indexOf(part); at >= 0; at = text.indexOf(part, at + 1)) count++;
        return count;
    }
}
